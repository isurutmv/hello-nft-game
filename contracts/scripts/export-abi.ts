import { artifacts } from "hardhat";
import fs from "node:fs";
import path from "node:path";

/** Writes typed ABIs for the web app to ../web/src/contracts/abi.ts. */
async function main() {
  const names = ["DashPacks", "DashCards", "PackRipper", "CardRenderer", "MockDogeDash", "MockStablecoin"];
  let out = "// Generated by contracts/scripts/export-abi.ts. Do not edit.\n";
  for (const name of names) {
    const { abi } = await artifacts.readArtifact(name);
    out += `\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  }
  const dir = path.join(__dirname, "..", "..", "web", "src", "contracts");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "abi.ts"), out);
  console.log(`Wrote ${names.length} ABIs to web/src/contracts/abi.ts`);
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
